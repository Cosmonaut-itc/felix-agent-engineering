            for name in ('rack','pueue-desk'):
                shutil.copytree(FLEET/name,root/name,ignore=shutil.ignore_patterns('__pycache__','*.pyc'))
            target=root/directory/relative
            source=target.read_text()
            # One safety rule can have two defensive checks; remove both together.
            edits = zip(original,replacement) if isinstance(original,tuple) else [(original,replacement)]
            for before,after in edits:
                if source.count(before)!=1:
                    raise AssertionError('Nonunique mutation anchor '+str(number)+': '+repr(before))
                source=source.replace(before,after)
            target.write_text(source)
            module = 'test_mode.' if test.startswith('Mode') else 'test_desk_slots.' if test.startswith('Desk') else 'test_slots_install.' if test.startswith('SlotsInstallTests.') else 'test_slots.'
